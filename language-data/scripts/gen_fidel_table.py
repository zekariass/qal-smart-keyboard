#!/usr/bin/env python3
"""Generate the Ethiopic syllable table from Unicode character names (plan step C1.3).

Source of truth: `unicodedata.name()` over the Ethiopic blocks, NOT code point arithmetic
(the blocks have irregular gaps and extra forms). Names look like `ETHIOPIC SYLLABLE GWAA`.

Outputs (deterministic, byte-for-byte reproducible; stdlib only):
  language-data/generated/fidel-table-v1.json   consumed by layout tooling (L1.x) and tests
  core/src/composer/fidel_table.rs              the same table compiled into the core

Usage:
  python language-data/scripts/gen_fidel_table.py           # write both files
  python language-data/scripts/gen_fidel_table.py --check   # exit 1 if a file is stale
"""
import json
import re
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT_JSON = ROOT / "language-data" / "generated" / "fidel-table-v1.json"
OUT_RS = ROOT / "core" / "src" / "composer" / "fidel_table.rs"

BLOCKS = [
    (0x1200, 0x137F),  # Ethiopic
    (0x1380, 0x139F),  # Ethiopic Supplement
    (0x2D80, 0x2DDF),  # Ethiopic Extended
    (0xAB00, 0xAB2F),  # Ethiopic Extended-A
    (0x1E7E0, 0x1E7FF),  # Ethiopic Extended-B (Unicode 14+)
]

# Vowel-order ids as they appear at the end of Unicode names, with the order number used by
# layouts. 1..7 are the traditional seven orders; 8 is the labialised "wa" form; 9 is the
# rare "oa" variant.
ORDERS = [
    ("A", 1),
    ("U", 2),
    ("I", 3),
    ("AA", 4),
    ("EE", 5),
    ("E", 6),
    ("O", 7),
    ("WA", 8),
    ("OA", 9),
]
# Longest suffix first so AA/EE/WA/OA win over A/E.
SUFFIXES = ["WA", "OA", "AA", "EE", "A", "U", "I", "E", "O"]

# Irregular labiovelar series: the name is <series>W + vowel, and the series carries its own
# orders (A, I, AA, EE, E). Generic parsing would read QWA as Q + WA.
LABIOVELAR = ["QHW", "KXW", "GGW", "QW", "KW", "XW", "GW"]

PREFIXES = ["GLOTTAL", "PHARYNGEAL", "SEBATBEIT", "GURAGE"]
BS = chr(92)  # backslash, for Rust '\u{..}' literals
NAME_RE = re.compile(r"^ETHIOPIC SYLLABLE ([A-Z ]+)$")


def parse(name):
    """`GWAA` -> ("GW", "AA"); `GLOTTAL A` -> ("GLOTTAL", "A"); `GURAGE QWI` -> ("GURAGE_QW", "I")."""
    toks = name.split(" ")
    prefix = ""
    if len(toks) == 2 and toks[0] in ("GLOTTAL", "PHARYNGEAL"):
        return toks[0], toks[1]
    if len(toks) == 2 and toks[0] in ("SEBATBEIT", "GURAGE"):
        prefix, body = toks[0] + "_", toks[1]
    elif len(toks) == 1:
        body = toks[0]
    else:
        raise ValueError("unexpected syllable name: " + name)
    for lab in LABIOVELAR:
        if body.startswith(lab) and body[len(lab):] in ("A", "I", "AA", "EE", "E"):
            return prefix + lab, body[len(lab):]
    for suf in SUFFIXES:
        if body.endswith(suf) and len(body) > len(suf):
            return prefix + body[: -len(suf)], suf
    raise ValueError("cannot parse syllable name: " + name)


def build():
    order_ids = {o for o, _ in ORDERS}
    series = {}
    first_cp = {}
    for lo, hi in BLOCKS:
        for cp in range(lo, hi + 1):
            name = unicodedata.name(chr(cp), "")
            m = NAME_RE.match(name)
            if not m:
                continue
            sid, order = parse(m.group(1))
            if order not in order_ids:
                raise ValueError("unknown order " + order)
            forms = series.setdefault(sid, {})
            if order in forms:
                raise ValueError("duplicate %s/%s (U+%04X)" % (sid, order, cp))
            forms[order] = cp
            first_cp.setdefault(sid, cp)
    ordered = sorted(series, key=lambda s: first_cp[s])
    return {
        "version": 1,
        "source": "unicodedata.name() over the Ethiopic blocks",
        "orders": [{"id": o, "number": n} for o, n in ORDERS],
        "series": [
            {
                "id": sid,
                "forms": {o: "U+%04X" % series[sid][o] for o, _ in ORDERS if o in series[sid]},
            }
            for sid in ordered
        ],
    }


def render_json(table):
    return json.dumps(table, indent=1, ensure_ascii=False) + "\n"


def render_rs(table):
    lines = [
        "//! GENERATED by language-data/scripts/gen_fidel_table.py from Unicode character names.",
        "//! Do not edit; regenerate and commit (a test fails when this file is stale).",
        "",
        "/// Vowel-order ids with their order numbers (1..=9).",
        "#[rustfmt::skip]",
        "pub static ORDERS: &[(&str, u8)] = &[",
    ]
    for o in table["orders"]:
        lines.append('    ("%s", %d),' % (o["id"], o["number"]))
    lines += [
        "];",
        "",
        "/// Consonant series in code point order: `(series id, [(order id, character)])`.",
        "#[rustfmt::skip]",
        "pub static SERIES: &[(&str, &[(&str, char)])] = &[",
    ]
    for s in table["series"]:
        forms = ", ".join(
            "(\"%s\", '%su{%X}')" % (o, BS, int(cp[2:], 16)) for o, cp in s["forms"].items()
        )
        lines.append('    ("%s", &[%s]),' % (s["id"], forms))
    lines += ["];", ""]
    return "\n".join(lines)


def outputs():
    t = build()
    return {OUT_JSON: render_json(t), OUT_RS: render_rs(t)}


def main(argv):
    outs = outputs()
    if "--check" in argv:
        stale = [
            str(p)
            for p, text in outs.items()
            if not p.exists() or p.read_bytes() != text.encode("utf-8")
        ]
        if stale:
            print("stale (run gen_fidel_table.py): " + ", ".join(stale), file=sys.stderr)
            return 1
        print("fidel table up to date")
        return 0
    for p, text in outs.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(text.encode("utf-8"))  # LF endings on every platform
        print("wrote", p.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
