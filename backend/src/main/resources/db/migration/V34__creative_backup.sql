-- T8.15 S1 (ADR 0050): opt-in, consent-gated, encrypted cloud backup of creative assets (Draw & Sketch drawings first).
--
-- 1. user_consents.consent_code: the new purpose CREATIVE_BACKUP (contract ConsentCode, ConsentType). Off unless
--    granted (no row = not granted); withdrawing it deletes every backed-up item of the user (ADR 0050).
-- 2. creative_backup_items: one row per backed-up item. The content is an opaque blob produced by the client and is
--    stored ONLY as ciphertext under the user's data key (ADR 0005; AAD: creative_backup_items, content_ciphertext,
--    row id), so crypto-shredding the account makes it unreadable. The plaintext columns are listing metadata only:
--    the client's item id, the kind, the server-assigned revision, the plaintext size, the client's last-modified time
--    and the server's times. No name, title or other content field exists on purpose.
--    The kind list is extended by a later migration (STICKER, CARD, ... when those tools get a backup).

ALTER TABLE user_consents DROP CONSTRAINT user_consents_consent_code_check;
ALTER TABLE user_consents ADD CONSTRAINT user_consents_consent_code_check CHECK (consent_code IN (
    'TERMS_ACCEPTANCE', 'PRIVACY_NOTICE', 'AI_PROCESSING', 'PAYMENT_MANDATE',
    'SAVE_AI_HISTORY', 'SAVE_AUDIO_HISTORY', 'DICTIONARY_SYNC', 'PERSONAL_STYLE',
    'FEEDBACK_TEXT', 'COMMUNITY_CONTRIBUTION', 'ANALYTICS', 'MARKETING',
    'CREATIVE_BACKUP'
));

CREATE TABLE creative_backup_items (
    id                  UUID PRIMARY KEY,   -- generated by the application before the insert: part of the AAD
    user_id             UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    client_item_id      VARCHAR(64) NOT NULL CHECK (client_item_id ~ '^[A-Za-z0-9_-]{1,64}$'),
    item_kind           VARCHAR(20) NOT NULL CHECK (item_kind IN ('DRAWING')),
    revision            BIGINT NOT NULL CHECK (revision > 0),
    content_ciphertext  BYTEA NOT NULL,
    key_version         INTEGER NOT NULL CHECK (key_version > 0),
    size_bytes          INTEGER NOT NULL CHECK (size_bytes > 0),
    client_updated_at   TIMESTAMPTZ NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ux_creative_backup_user_item UNIQUE (user_id, client_item_id),
    -- 33 bytes is the v1 envelope overhead (ADR 0005): a ciphertext shorter than its plaintext is not one
    CONSTRAINT ck_creative_backup_sealed CHECK (octet_length(content_ciphertext) >= size_bytes + 33)
);

CREATE INDEX ix_creative_backup_user_kind
    ON creative_backup_items (user_id, item_kind, client_item_id);

COMMENT ON TABLE creative_backup_items IS
    'Opt-in creative-asset backup (ADR 0050, CREATIVE_BACKUP consent). Content is ciphertext only; deleted on consent withdrawal and account deletion.';
COMMENT ON COLUMN creative_backup_items.content_ciphertext IS
    'Client-produced item content; ciphertext under the user data key (AAD: creative_backup_items, content_ciphertext, row id).';
COMMENT ON COLUMN creative_backup_items.size_bytes IS
    'Plaintext size in bytes (for the per-item and per-user caps and the usage summary).';
COMMENT ON COLUMN creative_backup_items.client_updated_at IS
    'Last-modified time reported by the client (the client decides which copy is newer); not checked by the server.';
