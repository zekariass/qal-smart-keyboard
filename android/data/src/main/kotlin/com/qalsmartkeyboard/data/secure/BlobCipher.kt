package com.qalsmartkeyboard.data.secure

import java.security.GeneralSecurityException
import javax.crypto.Cipher
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/** Authenticated encryption of one blob. Implementations never log or retain the plaintext. */
interface BlobCipher {
    /** Encrypts [plain]; [aad] is authenticated but not stored, so a blob only opens for the same [aad]. */
    fun encrypt(plain: ByteArray, aad: ByteArray): ByteArray

    /** Throws [GeneralSecurityException] for a wrong key, a changed blob or a different [aad]. */
    fun decrypt(blob: ByteArray, aad: ByteArray): ByteArray
}

/**
 * AES-256-GCM with a fresh random 96-bit IV per blob. Blob layout: `version(1) | ivLength(1) | iv | ciphertext+tag`.
 *
 * [key] supplies the key on every call: the Android Keystore key in production
 * ([KeystoreKeys.aesGcm], non-exportable), any `SecretKey` in JVM tests. The IV is generated by the
 * provider (required for Keystore keys, which refuse caller-supplied IVs when encrypting).
 */
class AesGcmCipher(private val key: () -> SecretKey) : BlobCipher {
    override fun encrypt(plain: ByteArray, aad: ByteArray): ByteArray {
        val c = Cipher.getInstance(TRANSFORMATION)
        c.init(Cipher.ENCRYPT_MODE, key())
        c.updateAAD(aad)
        val body = c.doFinal(plain)
        val iv = c.iv
        if (iv == null || iv.size !in 1..255) throw GeneralSecurityException("no IV")
        return byteArrayOf(VERSION, iv.size.toByte()) + iv + body
    }

    override fun decrypt(blob: ByteArray, aad: ByteArray): ByteArray {
        if (blob.size < 2 || blob[0] != VERSION) throw GeneralSecurityException("unknown format")
        val ivLen = blob[1].toInt() and 0xFF
        if (ivLen == 0 || blob.size < 2 + ivLen + TAG_BYTES) throw GeneralSecurityException("truncated")
        val c = Cipher.getInstance(TRANSFORMATION)
        c.init(Cipher.DECRYPT_MODE, key(), GCMParameterSpec(TAG_BYTES * 8, blob, 2, ivLen))
        c.updateAAD(aad)
        return c.doFinal(blob, 2 + ivLen, blob.size - 2 - ivLen)
    }

    private companion object {
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val VERSION: Byte = 1
        const val TAG_BYTES = 16
    }
}
