import groovy.json.JsonSlurper

plugins {
    alias(libs.plugins.android.library)
}

// ---------------------------------------------------------------------------------------------
// Pack trust anchors (plan A1.6). The keys the pack manager trusts are compiled into
// `PackTrustConfig` by this task; they are never read from a file shipped next to the packs.
//   debug:   the DEV key named in src/main/assets/packs/seed-packs.json (DRAFT seed packs).
//   release: the keys file given with -Pqal.packTrustKeysFile=<path>, JSON
//            {"keys":[{"id":"...","publicKeyHex":"<64 hex>","status":"ACTIVE|RETIRING|REVOKED","devOnly":false}]}.
//            Without it the build falls back to seed-packs.json and FAILS while that key is
//            DEV-only, unless -Pqal.allowDevPackKeys=true is passed (internal test builds only).
// ---------------------------------------------------------------------------------------------
abstract class GeneratePackTrustConfig : DefaultTask() {
    @get:InputFile
    abstract val seedIndex: RegularFileProperty

    @get:InputFile
    @get:Optional
    abstract val keysFile: RegularFileProperty

    @get:Input
    abstract val release: Property<Boolean>

    @get:Input
    abstract val allowDevKeys: Property<Boolean>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        data class K(val id: String, val hex: String, val status: String, val devOnly: Boolean)

        val keys: List<K> = if (keysFile.isPresent) {
            val root = JsonSlurper().parse(keysFile.get().asFile) as Map<*, *>
            (root["keys"] as List<*>).map {
                val m = it as Map<*, *>
                K(m["id"] as String, m["publicKeyHex"] as String, (m["status"] as String?) ?: "ACTIVE", (m["devOnly"] as Boolean?) ?: false)
            }
        } else {
            val m = JsonSlurper().parse(seedIndex.get().asFile) as Map<*, *>
            listOf(K(m["signingKeyId"] as String, m["signingPublicKeyHex"] as String, "ACTIVE", (m["signingKeyIsDevOnly"] as Boolean?) ?: true))
        }
        for (k in keys) {
            if (!Regex("[A-Za-z0-9._-]{1,120}").matches(k.id) || !Regex("[0-9a-f]{64}").matches(k.hex) ||
                k.status !in listOf("ACTIVE", "RETIRING", "REVOKED")
            ) {
                throw GradleException("invalid pack trust key entry '${k.id}'")
            }
        }
        if (keys.none { it.status != "REVOKED" }) throw GradleException("no usable pack trust key configured")
        if (release.get() && !allowDevKeys.get() && keys.any { it.devOnly }) {
            throw GradleException(
                "Release build refused: only DEV pack signing keys are configured (signingKeyIsDevOnly). " +
                    "Provide production keys with -Pqal.packTrustKeysFile=<keys.json>, or pass " +
                    "-Pqal.allowDevPackKeys=true for an internal test build.",
            )
        }
        val dir = outputDir.get().asFile.resolve("com/qalsmartkeyboard/ime/packs")
        dir.mkdirs()
        val list = keys.joinToString(",\n") {
            "        TrustKey(\"${it.id}\", \"${it.hex}\", ${it.devOnly}, uniffi.qal_keyboard_core.KeyStatus.${it.status})"
        }
        dir.resolve("PackTrustConfig.kt").writeText(
            """// Generated by GeneratePackTrustConfig (android/ime/build.gradle.kts). Do not edit.
package com.qalsmartkeyboard.ime.packs

internal object PackTrustConfig {
    val KEYS: List<TrustKey> = listOf(
$list,
    )

    const val ALLOW_DEV_KEYS_IN_RELEASE: Boolean = ${allowDevKeys.get()}
}
""",
        )
    }
}

androidComponents {
    onVariants { variant ->
        val name = variant.name.replaceFirstChar { it.uppercase() }
        val task = tasks.register<GeneratePackTrustConfig>("generate${name}PackTrustConfig") {
            seedIndex.set(layout.projectDirectory.file("src/main/assets/packs/seed-packs.json"))
            providers.gradleProperty("qal.packTrustKeysFile").orNull?.let { keysFile.set(rootProject.layout.projectDirectory.file(it)) }
            release.set(variant.buildType == "release")
            allowDevKeys.set(providers.gradleProperty("qal.allowDevPackKeys").map { it == "true" }.orElse(false))
            outputDir.set(layout.buildDirectory.dir("generated/qal/packTrust/${variant.name}"))
        }
        variant.sources.kotlin?.addGeneratedSourceDirectory(task, GeneratePackTrustConfig::outputDir)
    }
}

android {
    namespace = "com.qalsmartkeyboard.ime"
    compileSdk {
        version = release(36) {
            minorApiLevel = 1
        }
    }

    defaultConfig {
        minSdk = providers.gradleProperty("qal.minSdk").get().toInt()
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_11
        targetCompatibility = JavaVersion.VERSION_11
    }
}

// JVM unit tests that drive the real core (end-to-end typing over the bundled packs) load the
// host build of the Rust library through JNA, like :core-bindings' own unit test.
tasks.withType<Test>().configureEach {
    dependsOn(":core-bindings:cargoHostBuild")
    systemProperty("jna.library.path", rootProject.layout.projectDirectory.dir("../core/target/release").asFile.absolutePath)
}

dependencies {
    implementation(project(":core-bindings"))
    implementation(libs.androidx.core.ktx)
    testImplementation(libs.junit)
    testImplementation(libs.jna.jvm)
}
