    val free: List<KeyboardTheme> = all.filter { it.tier == ThemeTier.FREE }
    val premium: List<KeyboardTheme> = all.filter { it.tier == ThemeTier.PREMIUM }

    val classicLight: KeyboardTheme = all.first { it.id == CLASSIC_LIGHT_ID }
    val classicDark: KeyboardTheme = all.first { it.id == CLASSIC_DARK_ID }

    private val byId: Map<String, KeyboardTheme> = all.associateBy { it.id }

    /** The theme with this id, or null for [SYSTEM_ID] and for ids this build does not know. */
    fun find(id: String?): KeyboardTheme? = byId[id]

    /** Classic Light or Classic Dark: what "System" shows and what a theme that is not available falls back to. */
    fun classic(light: Boolean): KeyboardTheme = if (light) classicLight else classicDark

    private const val WARN_LIGHT = 0xFF8A5100
    private const val WARN_DARK = 0xFFFFB74D

    /**
     * Builder with the shared rules: the strip follows the background's top colour, popups follow the key fill,
     * a shadow is a one-dp offset of [shadow] at about one third opacity, a border is one dp wide.
     * Colour arguments are `0xAARRGGBB` longs (Kotlin cannot write them as Int literals).
     */
    private fun theme(
        id: String,
        name: String,
        tier: ThemeTier,
        isLight: Boolean,
        bgTop: Long,
        bgBottom: Long = bgTop,
        key: Long,
        special: Long,
        pressed: Long,
        accent: Long,
        onAccent: Long,
        accentText: Long,
        keyText: Long,
        specialText: Long = keyText,
        hintText: Long,
        border: Long = 0,
        shadow: Long = 0,
        cornerRadiusDp: Float,
    ) = KeyboardTheme(
        id = id,
        name = name,
        tier = tier,
        isLight = isLight,
        bgTop = bgTop.toInt(),
        bgBottom = bgBottom.toInt(),
        key = key.toInt(),
        special = special.toInt(),
        pressed = pressed.toInt(),
        accent = accent.toInt(),
        onAccent = onAccent.toInt(),
        accentText = accentText.toInt(),
        keyText = keyText.toInt(),
        specialText = specialText.toInt(),
        hintText = hintText.toInt(),
        border = border.toInt(),
        borderWidthDp = if (border != 0L) 1f else 0f,
        shadow = if (shadow != 0L) ((shadow and 0xFFFFFF) or 0x55000000).toInt() else 0,
        shadowDyDp = if (shadow != 0L) 1f else 0f,
        cornerRadiusDp = cornerRadiusDp,
        stripBg = bgTop.toInt(),
        stripText = keyText.toInt(),
        stripDivider = special.toInt(),
        warn = (if (isLight) WARN_LIGHT else WARN_DARK).toInt(),
        popupBg = key.toInt(),
        popupText = keyText.toInt(),
        popupBorder = pressed.toInt(),
    )
}
